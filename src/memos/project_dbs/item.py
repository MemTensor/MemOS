"""Data structures exchanged with the project memory storage layer."""

from datetime import datetime
from typing import Annotated, Any, Generic, Literal, TypeVar

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, JsonValue


T = TypeVar("T")


class Message(BaseModel):
    """Stored source message; shared by all spaces that reference its turn."""

    project_id: str
    conversation_key: str
    message_id: str
    conversation_id: str | None = None
    turn_id: str
    turn_seq: int
    msg_seq: int
    role: Literal["user", "assistant", "tool", "system"]
    role_id: str | None = None
    role_name: str | None = None
    content: str
    tool_calls: JsonValue = None
    tool_call_id: str | None = None
    experience_notes: JsonValue = None
    chat_time: AwareDatetime
    accepted_at: AwareDatetime
    task_id: str
    user_id: str
    agent_id: str | list[str] | None = None
    content_sha256: str


class Episode(BaseModel):
    """Accumulation, extraction, and commit state for a sequence of turns in one space."""

    id: str
    space_id: str
    project_id: str
    conversation_key: str
    conversation_id: str | None = None
    user_id: str
    domains: list[str]
    previous_episode_id: str | None = None
    state: Literal["open", "closed", "extracting", "extracted"]
    close_reason: (
        Literal["task_boundary", "idle", "turn_count", "max_wait", "volume", "no_conversation"]
        | None
    ) = None
    opened_at: AwareDatetime
    last_turn_at: AwareDatetime
    idle_due_at: AwareDatetime | None = None
    max_wait_due_at: AwareDatetime | None = None
    closed_at: AwareDatetime | None = None
    dispatched_at: AwareDatetime | None = None
    suspected_boundary_turn_ids: list[str] = Field(default_factory=list)
    extract_status: Literal["drafted", "skipped", "failed"] | None = None
    episode_summary: str | None = None
    drafts: list[dict[str, JsonValue]] = Field(default_factory=list)
    anchors: list[dict[str, JsonValue]] = Field(default_factory=list)
    anchor_keys: list[str] = Field(default_factory=list)
    extracted_at: AwareDatetime | None = None
    stage: Literal[
        "episode_open",
        "extracting",
        "organizing_queued",
        "organizing",
        "awaiting_merge",
        "committing",
        "retry_wait",
        "done",
    ]
    attempt: int = 0
    organize_result: dict[str, JsonValue] | None = None
    commit_key: str | None = None
    outcome: Literal["pending", "committed", "staged", "skipped", "failed"] = "pending"
    result: dict[str, JsonValue] | None = None
    created_topic_ids: list[str] = Field(default_factory=list)
    next_retry_at: AwareDatetime | None = None
    error: dict[str, JsonValue] | None = None
    last_error: dict[str, JsonValue] | None = None
    warnings: list[JsonValue] = Field(default_factory=list)
    staged_status: Literal["active", "moved", "archived", "long_unassigned"] | None = None
    staged_domain_id: str | None = None
    staged_reason: str | None = None
    staged_at: AwareDatetime | None = None
    staged_attempts: int = 0
    moved_to_topic_id: str | None = None
    staged_tsv: str | None = None
    staged_embedding: list[float] | None = None
    updated_at: AwareDatetime


class EpisodeTurn(BaseModel):
    """A turn's episode and task assignment within one space."""

    space_id: str
    conversation_key: str
    turn_id: str
    project_id: str
    episode_id: str
    turn_seq: int
    message_count: int
    task_id: str
    user_id: str
    agent_id: str | list[str] | None = None
    chat_time: AwareDatetime
    accepted_at: AwareDatetime


class Space(BaseModel):
    id: str
    project_id: str
    space_name: str
    instructions: str | None = None
    create_time: datetime
    update_time: datetime
    cleared_at: datetime | None = None  # last time the space memory was cleared


class Domain(BaseModel):
    id: str | None = None  # generated by storage; empty on create
    space_id: str | None = None
    domain: str
    description: str = ""


class DomainUpdate(BaseModel):  # one item of update/domains
    domain: str  # name before the change
    new_domain: str | None = None
    description: str | None = None  # empty string clears the description


class EntrySource(BaseModel):  # where a conclusion or piece of evidence came from
    conversation_id: str | None = None
    message_id: str | None = None
    quote: str | None = None  # original wording


class Entry(BaseModel):  # common entry fields, one project_entries row
    id: str | None = None  # generated by storage; empty when adding
    entry_type: Literal["decision", "experience", "timeline"]
    content: str
    time: AwareDatetime  # timezone required
    user_ids: list[str]
    version: int = 1  # managed by storage; ignored on write
    create_time: datetime | None = None  # filled by storage; ignored on write
    update_time: datetime | None = None  # filled by storage; update/memory sends it back
    embedding: list[float] | None = Field(default=None, exclude=True)  # write-only


# ---------- decision ----------
class HistoryItem(BaseModel):  # one item of the history column: a superseded conclusion
    content: str
    time: datetime
    user_ids: list[str]
    reason: str | None = None
    source: EntrySource | None = None  # source of the superseded conclusion
    change_source: EntrySource | None = None  # message that superseded it
    # pending algorithm decision
    commit_key: str | None = None


class ConflictItem(BaseModel):  # one item of the conflicts column: an unresolved conclusion
    content: str
    time: datetime
    user_ids: list[str]
    source: EntrySource | None = None
    # pending algorithm decision
    seq: int | None = None


class DecisionExtra(BaseModel):  # extra column of a decision
    source: EntrySource | None = None  # source of the current conclusion
    # pending algorithm decision
    category: str | None = None
    reason: str | None = None


class Decision(Entry):
    entry_type: Literal["decision"] = "decision"
    history: list[HistoryItem] = Field(default_factory=list)
    conflicts: list[ConflictItem] = Field(default_factory=list)
    extra: DecisionExtra = Field(default_factory=DecisionExtra)


# ---------- experience (extra pending algorithm decision) ----------
class ExperienceCard(BaseModel):  # content is built as task_intent | problem | principle
    task_intent: str
    problem: str
    principle: str
    technical_context: str | None = None
    failed_shape: str | None = None
    validation: str | None = None
    anchors: list[str] = Field(default_factory=list)


class ExperienceEvidence(BaseModel):  # one piece of evidence for an experience
    conversation_id: str | None = None
    message_id: str | None = None
    role: str | None = None
    role_id: str | None = None
    chat_time: datetime | None = None
    content: str | None = None
    segment_id: str | None = None  # episode id
    quality_score: float | None = None
    signal: str | None = None
    action: str | None = None
    injected: bool | None = None


class ExperienceCardVersion(BaseModel):  # an earlier card version
    version: int
    card: dict[str, Any]  # changed card fields only
    time: datetime
    commit_key: str | None = None


class ExperienceExtra(BaseModel):  # extra column of an experience
    card: ExperienceCard | None = None
    exp_status: str | None = None
    confidence: float | None = None
    signal: str | None = None
    quality_score: float | None = None
    last_supported_at: datetime | None = None
    use_count: int = 0
    sources: list[ExperienceEvidence] = Field(default_factory=list)
    history: list[ExperienceCardVersion] = Field(default_factory=list)


class Experience(Entry):
    entry_type: Literal["experience"] = "experience"
    extra: ExperienceExtra = Field(default_factory=ExperienceExtra)


# ---------- timeline ----------
class TimelineExtra(BaseModel):  # extra column of a timeline entry
    # pending algorithm decision
    episode_id: str | None = None


class Timeline(Entry):
    entry_type: Literal["timeline"] = "timeline"
    extra: TimelineExtra = Field(default_factory=TimelineExtra)


AnyEntry = Annotated[Decision | Experience | Timeline, Field(discriminator="entry_type")]


# ---------- topics ----------
class Source(BaseModel):  # source conversation, raw external values
    user_id: str | list[str]
    agent_id: str | list[str] | None = None
    conversation_id: str | None = None


class Topic(BaseModel):
    id: str  # generated by storage, prefixed with topic_
    space_id: str
    domain: str  # domain name; stored as domain_id
    topic_name: str
    topic_summary: str
    topic_description: str
    # Assembled from project_entries: list_topics returns at most preview_size per type
    # without history/conflicts; get_topics returns all entries.
    decisions: list[Decision] = Field(default_factory=list)
    experiences: list[Experience] = Field(default_factory=list)
    timeline: list[Timeline] = Field(default_factory=list)
    sources: list[Source] = Field(default_factory=list)
    create_time: datetime
    update_time: datetime
    version: int = 1  # optimistic lock
    # pending algorithm decision
    anchors: list[dict[str, Any]] = Field(default_factory=list)
    anchor_keys: list[str] = Field(default_factory=list)


class TimeRange(BaseModel):
    model_config = ConfigDict(extra="forbid")  # reject unknown keys

    gt: AwareDatetime | None = None  # timezone required
    gte: AwareDatetime | None = None
    lt: AwareDatetime | None = None
    lte: AwareDatetime | None = None


class TopicFilter(BaseModel):
    """One AND group: create_time and update_time must both match.

    Storage takes list[TopicFilter]; groups are ORed. The handler expands the
    external and/or expression into that list, e.g.
    {"and": [A, {"or": [B, C]}]} -> [A and B, A and C].
    """

    model_config = ConfigDict(extra="forbid")  # an unknown key must not mean "match all"

    create_time: TimeRange | None = None
    update_time: TimeRange | None = None


# ---------- organizer output ----------
class TopicCreate(BaseModel):  # create one topic
    model_config = ConfigDict(extra="forbid")  # reject unknown keys

    domain: str  # must be registered in the space
    topic_name: str
    topic_summary: str
    topic_description: str
    entries: list[AnyEntry] = Field(default_factory=list)  # ids empty, generated by storage
    sources: list[Source] = Field(default_factory=list)
    embedding: list[float] | None = None
    # pending algorithm decision
    anchors: list[dict[str, Any]] = Field(default_factory=list)


class TopicUpdate(BaseModel):  # update one topic; omitted fields are kept
    model_config = ConfigDict(extra="forbid")  # reject unknown keys

    topic_id: str
    expected_version: int  # version read by the organizer; mismatch rolls back the batch
    domain: str | None = None  # change domain; must be registered in the space
    topic_summary: str | None = None
    topic_description: str | None = None
    upsert_entries: list[AnyEntry] = Field(default_factory=list)  # no id: add; id: replace
    delete_entry_ids: list[str] = Field(default_factory=list)
    add_sources: list[Source] = Field(default_factory=list)  # deduplicated by storage
    embedding: list[float] | None = None
    # pending algorithm decision
    anchors: list[dict[str, Any]] | None = None  # replaces all; anchor_keys derived by storage


class TopicChangeSet(BaseModel):  # all changes of one organize run in a space, one transaction
    model_config = ConfigDict(extra="forbid")  # reject unknown keys

    space_id: str
    accepted_at: AwareDatetime  # task acceptance time; not after spaces.cleared_at -> rejected
    creates: list[TopicCreate] = Field(default_factory=list)
    updates: list[TopicUpdate] = Field(default_factory=list)


class TopicChangeResult(BaseModel):  # reported back as change events
    topic_id: str
    operation: Literal["ADD", "UPDATE"]


# ---------- search ----------
class SearchHit(BaseModel):  # candidate topic from search_topics
    topic: Topic
    score: float  # raw recall score; ranking is done by retrieval


class EntryHit(BaseModel):  # candidate entry from search_entries
    entry: AnyEntry
    topic_id: str
    score: float


class Page(BaseModel, Generic[T]):
    items: list[T]
    total: int
    page: int
    size: int
