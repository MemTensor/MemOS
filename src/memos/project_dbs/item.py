"""Data structures exchanged with the project memory storage layer.

Follows the reviewed table spec (项目记忆算法部分表结构评审). JSONB objects are JsonPart (unknown
keys kept as is); write and filter parameters are StrictModel (unknown keys rejected).
"""

from datetime import datetime
from enum import IntEnum
from typing import Annotated, Generic, Literal, TypeVar

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field


T = TypeVar("T")


class JsonPart(BaseModel):  # an object inside JSONB: undeclared keys are kept as is
    model_config = ConfigDict(extra="allow")


class StrictModel(BaseModel):  # write and filter parameters: unknown keys are errors
    model_config = ConfigDict(extra="forbid")


# ---------- spaces and domains ----------
class Space(BaseModel):  # one spaces row; Add-only columns (resource_bindings, Formation) excluded
    id: str
    project_id: str
    space_name: str
    instructions: str | None = None
    create_time: datetime
    update_time: datetime
    clear_time: datetime | None = None  # last time the space memory was cleared


class Domain(BaseModel):  # one domains row
    id: str | None = None  # generated by storage; empty on create
    space_id: str | None = None
    domain: str  # domain name, unique within the space
    description: str = ""


class DomainUpdate(BaseModel):  # one item of update/domains
    domain_id: str  # the domain to change; a rename keeps the ID
    new_domain: str | None = None
    description: str | None = None  # empty string clears the description


# ---------- entries: common ----------
class EntryStatus(IntEnum):  # project_entries.status
    ACTIVE = 0  # currently valid
    ARCHIVED = 1  # superseded (old decision conclusion) or retired (experience)
    CONFLICT = 2  # conflicts with the current conclusion, unresolved; decisions only


class EntrySource(JsonPart):  # where a conclusion came from: one quote and its location
    conversation_id: str | None = None  # caller conversation id; None without one
    message_id: str | None = None  # points to messages.message_id
    episode_id: str | None = None  # containing Episode; finds the quote without a conversation id
    quote: str | None = None  # original wording


class Entry(BaseModel):  # common columns of one project_entries row
    id: str | None = None  # generated by storage; empty when adding
    topic_id: str | None = None  # filled on read, ignored on write (TopicCreate/TopicUpdate own it)
    space_id: str | None = None  # same as topic_id
    entry_type: Literal["decision", "experience", "timeline"]
    status: EntryStatus = EntryStatus.ACTIVE  # filled on read; topics and search: ACTIVE only
    content: str  # decision / timeline <= 100 chars; experience built from the card, <= 200
    chat_time: AwareDatetime  # when it happened (message chat_time), timezone required
    user_ids: list[str]  # related members (external ids)
    version: int = 1  # managed by storage; ignored on write
    create_time: datetime | None = None  # filled by storage; ignored on write
    update_time: datetime | None = None  # filled by storage; update/memory sends it back exactly
    embedding: list[float] | None = Field(default=None, exclude=True)  # write-only
    extra: JsonPart = Field(default_factory=JsonPart)  # extra column; known keys per subclass


# ---------- decision ----------
# A decision is a group of rows: the current conclusion (ACTIVE), old conclusions (ARCHIVED)
# and conflicting conclusions (CONFLICT); child rows point to the current one through
# parent_decision_id. history / conflicts are not stored in extra: apply_changes writes them
# as child rows (history append-only, kept by id; conflicts replaced wholesale) and reads
# assemble them from the child rows.
class DecisionCard(BaseModel):  # one superseded conclusion; an ARCHIVED child row
    id: str | None = None  # child row id; generated by storage, empty when adding
    content: str  # child content column
    chat_time: AwareDatetime  # child chat_time column: when that conclusion was made
    user_ids: list[str]  # child user_ids column: owners at the time
    reason: str | None = None  # child extra: why it was superseded
    source: EntrySource | None = None  # child extra: where the old conclusion came from
    change_source: EntrySource | None = None  # child extra: the message that superseded it
    embedding: list[float] | None = Field(default=None, exclude=True)  # write-only


class ConflictCard(BaseModel):  # a conclusion that cannot hold with the current one; CONFLICT row
    id: str | None = None  # child row id; generated by storage; M05 refers to conflicts by it
    content: str  # child content column
    chat_time: AwareDatetime  # child chat_time column
    user_ids: list[str]  # child user_ids column: members supporting it
    source: EntrySource | None = None  # child extra: where it came from
    embedding: list[float] | None = Field(default=None, exclude=True)  # write-only


class DecisionExtra(JsonPart):  # extra column of the current conclusion
    sources: list[EntrySource] = Field(default_factory=list)  # replaced on rewrite / adoption
    user_labels: dict[str, str] = Field(default_factory=dict)  # member id -> display name


class Decision(Entry):  # the current conclusion row plus child rows assembled on read
    entry_type: Literal["decision"] = "decision"
    extra: DecisionExtra = Field(default_factory=DecisionExtra)
    history: list[DecisionCard] = Field(default_factory=list)  # ARCHIVED rows, oldest first
    conflicts: list[ConflictCard] = Field(default_factory=list)  # CONFLICT rows, oldest first


# ---------- experience ----------
class ExperienceCard(
    JsonPart
):  # content = task_intent, problem, principle joined by U+FF5C on write
    task_intent: str
    problem: str
    principle: str
    technical_context: str | None = None
    failed_shape: str | None = None
    validation: str | None = None  # how it was validated; must be found in the quotes
    anchors: list[str] = Field(default_factory=list)  # related files or modules


class ExperienceSource(EntrySource):  # one piece of evidence: add / confirm / update / refute
    role_id: str | None = None  # member who said it
    chat_time: AwareDatetime | None = None  # evidence message time; drives lifecycle staleness
    signal: Literal["test", "build", "review", "user", "none"] | None = None
    action: Literal["add", "confirm", "update", "refute"] | None = None


class ExperienceExtra(JsonPart):  # extra column of an experience
    card: ExperienceCard
    exp_status: Literal["verified", "candidate", "failed_attempt"] = "candidate"
    confidence: float = Field(default=0.5, ge=0.1, le=0.95)  # 0.5 when added
    sources: list[ExperienceSource] = Field(default_factory=list)


class Experience(Entry):
    entry_type: Literal["experience"] = "experience"
    extra: ExperienceExtra  # required: an experience must have a card


# ---------- timeline ----------
class TimelineExtra(JsonPart):  # extra column of a timeline entry: where it came from
    conversation_id: str | None = None
    message_ids: list[str] = Field(default_factory=list)  # point to messages.message_id
    episode_id: str | None = None
    role_id: str | None = None  # member who said it


class Timeline(Entry):
    entry_type: Literal["timeline"] = "timeline"
    extra: TimelineExtra = Field(default_factory=TimelineExtra)


AnyEntry = Annotated[Decision | Experience | Timeline, Field(discriminator="entry_type")]


# ---------- topics ----------
class Source(JsonPart):  # one item of the sources column: a source conversation
    conversation_id: str | None = None  # None merges writes without a conversation id
    user_id: list[str] = Field(default_factory=list)  # role_ids of the speaking members
    agent_id: str | None = None  # caller agent_id; None when not given


class Topic(BaseModel):  # one topics row plus entries assembled on read
    id: str  # generated by storage: topic_ + 32 hex
    space_id: str
    domain: str  # domain name; stored as domain_id
    topic_name: str
    topic_summary: str
    topic_description: str
    # assembled from project_entries (ACTIVE rows only)
    decisions: list[Decision] = Field(default_factory=list)
    experiences: list[Experience] = Field(default_factory=list)
    timeline: list[Timeline] = Field(default_factory=list)
    sources: list[Source] = Field(default_factory=list)
    create_time: datetime  # chat time: first message of the first Episode
    update_time: datetime  # chat time: last message of the latest Episode
    version: int = 1  # optimistic lock
    anchors: list[JsonPart] = Field(default_factory=list)  # structure pending the algorithm


class TimeRange(StrictModel):  # all bounds must be timezone-aware
    gt: AwareDatetime | None = None
    gte: AwareDatetime | None = None
    lt: AwareDatetime | None = None
    lte: AwareDatetime | None = None


class TopicFilter(StrictModel):
    """One AND group: create_time and update_time must both match.

    Storage takes list[TopicFilter]; groups are ORed. The handler expands the external
    and/or expression into that list, e.g. {"and": [A, {"or": [B, C]}]} -> [A and B, A and C].
    Only create_time and update_time exist this phase; other fields are rejected by the handler.
    """

    create_time: TimeRange | None = None
    update_time: TimeRange | None = None


# ---------- organizer output ----------
class TopicCreate(StrictModel):  # create one topic
    domain: str  # must be registered in the space
    topic_name: str
    topic_summary: str
    topic_description: str
    entries: list[AnyEntry] = Field(default_factory=list)  # ids empty, generated by storage
    sources: list[Source] = Field(default_factory=list)  # conversation_ids derived by storage
    create_time: AwareDatetime  # chat_time of the first message of the first Episode
    update_time: AwareDatetime  # chat_time of the last message of the latest Episode
    embedding: list[float] | None = None
    anchors: list[JsonPart] = Field(default_factory=list)  # anchor_keys derived by storage


class TopicUpdate(StrictModel):  # update one topic; omitted fields are kept
    topic_id: str
    expected_version: int  # version read by the organizer; mismatch rolls back the batch
    domain: str | None = None  # change domain; must be registered in the space
    topic_summary: str | None = None
    topic_description: str | None = None
    upsert_entries: list[AnyEntry] = Field(default_factory=list)  # no id: add; id: replace
    delete_entry_ids: list[str] = Field(default_factory=list)  # ACTIVE ids; children cascade
    add_sources: list[Source] = Field(default_factory=list)  # deduplicated; derived cols redone
    update_time: AwareDatetime | None = None  # last message chat_time of this Episode
    embedding: list[float] | None = None
    anchors: list[JsonPart] | None = None  # replaces all; anchor_keys derived by storage


class TopicChangeSet(StrictModel):  # all changes of one organize run in a space, one transaction
    space_id: str
    accept_time: AwareDatetime  # add_jobs.accept_time; not after spaces.clear_time -> rejected
    creates: list[TopicCreate] = Field(default_factory=list)
    updates: list[TopicUpdate] = Field(default_factory=list)


class TopicChangeResult(BaseModel):  # reported back as change events
    topic_id: str
    operation: Literal["ADD", "UPDATE"]


# ---------- search ----------
class SearchHit(BaseModel):  # candidate topic from search_topics_by_*
    topic: Topic
    score: float  # raw recall score; ranking and normalization happen in retrieval


class EntryHit(BaseModel):  # candidate entry from search_entries_by_*; see entry.topic_id
    entry: AnyEntry  # a child-row hit returns its decision
    score: float


class Page(BaseModel, Generic[T]):
    items: list[T]
    total: int
    page: int
    size: int


# ---------- Add: raw messages and Episodes (messages, episodes tables) ----------
class Message(BaseModel):  # one messages row: a raw message shared by all spaces
    project_id: str
    conversation_key: str  # the conversation id, or task:{task_id} without one
    message_id: str  # caller message id, generated on acceptance when missing
    msg_seq: int  # order within the conversation, from 1, assigned on acceptance
    role: Literal["user", "assistant", "tool", "system"]
    role_id: str | None = None  # speaking member; user messages default to the caller user_id
    role_name: str | None = None
    agent_id: str | None = None
    content: str  # cleaned text, stored in full
    tool_calls: list[JsonPart] | None = None
    tool_call_id: str | None = None
    experience_notes: list[JsonPart] | None = None
    chat_time: AwareDatetime
    accept_time: AwareDatetime  # first acceptance time
    task_id: str  # task that first accepted it
    content_sha256: str  # same id, different content -> MESSAGE_ID_CONFLICT


class Episode(BaseModel):  # one episodes row: consecutive messages of one conversation in a space
    id: str
    space_id: str
    conversation_key: str
    message_seq_start: int  # msg_seq of the first message (closed range)
    message_seq_end: int  # msg_seq of the last message (closed range), advanced while open
    previous_episode_id: str | None = None  # reopen plan B: previous Episode after clear_time
    topic_id: str | None = None  # topic it went to; None when not filed
    episode_summary: str | None = None  # M02 trajectory summary
    first_chat_time: AwareDatetime
    last_chat_time: AwareDatetime
    create_time: datetime | None = None  # filled by storage: first message acceptance time
    embedding: list[float] | None = Field(default=None, exclude=True)  # write-only
