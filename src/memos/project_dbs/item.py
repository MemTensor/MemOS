"""Data structures exchanged with the project memory storage layer."""

from datetime import datetime
from typing import Annotated, Any, Generic, Literal, TypeVar

from pydantic import BaseModel, Field


T = TypeVar("T")


class Space(BaseModel):
    id: str
    project_id: str
    space_name: str
    instructions: str | None = None
    create_time: datetime
    update_time: datetime


class Domain(BaseModel):
    id: str | None = None  # generated by storage; empty on create
    space_id: str | None = None
    domain: str
    description: str = ""


class DomainUpdate(BaseModel):  # one item of update/domains
    domain: str  # name before the change
    new_domain: str | None = None
    description: str | None = None  # empty string clears the description


class Entry(BaseModel):  # common entry fields, one project_entries row
    id: str | None = None  # generated by storage; empty when adding
    entry_type: Literal["decision", "experience", "timeline"]
    content: str
    time: datetime
    user_ids: list[str]
    embedding: list[float] | None = Field(default=None, exclude=True)  # write-only


class EntrySource(BaseModel):  # where a conclusion came from
    conversation_id: str | None = None
    message_id: str | None = None
    quote: str | None = None  # original wording


class HistoryItem(BaseModel):  # a superseded conclusion
    content: str
    time: datetime
    user_ids: list[str]
    reason: str | None = None
    source: EntrySource | None = None  # source of the superseded conclusion
    change_source: EntrySource | None = None  # message that superseded it


class ConflictItem(BaseModel):  # an unresolved differing conclusion
    content: str
    time: datetime
    user_ids: list[str]
    source: EntrySource | None = None


class Decision(Entry):  # entry_type = decision
    entry_type: Literal["decision"] = "decision"
    source: EntrySource | None = None
    history: list[HistoryItem] = Field(default_factory=list)
    conflicts: list[ConflictItem] = Field(default_factory=list)


class Experience(Entry):  # entry_type = experience
    entry_type: Literal["experience"] = "experience"
    extra: dict[str, Any] = Field(
        default_factory=dict
    )  # experience-specific fields, TBD with algorithm


class TimelineEntry(Entry):  # entry_type = timeline
    entry_type: Literal["timeline"] = "timeline"


AnyEntry = Annotated[Decision | Experience | TimelineEntry, Field(discriminator="entry_type")]


class Source(BaseModel):  # source conversation, raw external values
    user_id: str | list[str]
    agent_id: str | list[str] | None = None
    conversation_id: str | None = None


class Topic(BaseModel):
    id: str  # generated by storage, prefixed with topic_
    space_id: str
    domain: str  # domain name; stored as domain_id
    topic_name: str
    topic_summary: str
    topic_description: str
    decisions: list[Decision] = Field(default_factory=list)  # assembled from project_entries
    experiences: list[Experience] = Field(default_factory=list)
    timeline: list[TimelineEntry] = Field(default_factory=list)
    sources: list[Source] = Field(default_factory=list)
    create_time: datetime
    update_time: datetime


class TimeRange(BaseModel):
    gt: datetime | None = None
    gte: datetime | None = None
    lt: datetime | None = None
    lte: datetime | None = None


class TopicFilter(BaseModel):  # external filter converted by the handler
    op: Literal["and", "or"] = "and"
    user_ids: list[str] | None = None  # matches any source user_id
    agent_ids: list[str] | None = None  # matches any source agent_id
    create_time: TimeRange | None = None
    update_time: TimeRange | None = None
    children: list["TopicFilter"] = Field(default_factory=list)  # nested and / or


class SpaceContext(BaseModel):  # organizer input, returned by load_space_context
    space: Space  # includes instructions
    domains: list[Domain]  # candidate domains with descriptions
    topics: list[Topic]  # existing topics with entries


class TopicChange(BaseModel):  # organizer output: changes to one topic
    op: Literal["create", "update"]
    topic_id: str | None = None  # required for update; generated on create
    domain: str  # domain name, must be registered in the space
    # topic_name (create only), topic_summary, topic_description
    fields: dict[str, Any] = Field(default_factory=dict)
    upsert_entries: list[AnyEntry] = Field(default_factory=list)  # no id: add; with id: replace
    delete_entry_ids: list[str] = Field(default_factory=list)
    add_sources: list[Source] = Field(
        default_factory=list
    )  # appended sources, deduplicated by storage
    embedding: list[float] | None = None  # topic vector from the handler's embedder


class TopicChangeSet(BaseModel):  # all changes of one organize run in a space
    space_id: str
    changes: list[TopicChange]


class TopicChangeResult(BaseModel):  # reported back as change events
    topic_id: str
    operation: Literal["ADD", "UPDATE"]


class SearchHit(BaseModel):  # candidate topic from search_topics
    topic: Topic
    score: float  # raw recall score; ranking is done by retrieval


class EntryHit(BaseModel):  # candidate entry from search_entries
    entry: AnyEntry
    topic_id: str
    score: float


class Page(BaseModel, Generic[T]):
    items: list[T]
    total: int
    page: int
    size: int
