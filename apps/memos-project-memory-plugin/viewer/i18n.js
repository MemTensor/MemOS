let language = 'zh';
const bindings = new WeakMap();
const localized = render => ({ render, toString: render });
const isLocalized = value => value && typeof value.render === 'function';

// Keep interpolation values separate so user content is never translated as UI copy.
export function t(source, ...values) {
  return localized(() => (language === 'en' ? english[source] ?? source : source)
    .replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? '')));
}
export function joinText(values, separator = ' · ') {
  return localized(() => values.map(String).join(separator));
}
export function dateText(value, timeOnly = false) {
  return localized(() => {
    if (!value) return '—';
    const date = new Date(value), locale = language === 'en' ? 'en-US' : 'zh-CN';
    return timeOnly ? date.toLocaleTimeString(locale, { hour12: false }) : date.toLocaleString(locale, { hour12: false });
  });
}
function bind(node, property, value, attribute = false) {
  let slots = bindings.get(node);
  if (!slots) { slots = new Map(); bindings.set(node, slots); }
  const key = `${attribute ? 'attribute' : 'property'}:${property}`;
  if (isLocalized(value)) slots.set(key, { property, value, attribute });
  else slots.delete(key);
  if (attribute) node.setAttribute(property, String(value));
  else node[property] = String(value ?? '');
}
export function setText(node, value) { bind(node, 'textContent', value); }
export function attr(node, name, value) { bind(node, name, value, true); }

export function getLanguage() { return language; }
export function setLanguage(next, root = globalThis.document) {
  if (!['zh', 'en'].includes(next)) return;
  language = next;
  try { globalThis.window?.localStorage?.setItem('memos-viewer-language', language); } catch { /* Storage can be disabled. */ }
  if (!root) return;
  root.documentElement?.setAttribute('lang', language === 'en' ? 'en' : 'zh-CN');
  const update = node => {
    for (const { property, value, attribute } of bindings.get(node)?.values() ?? []) {
      if (attribute) node.setAttribute(property, String(value));
      else node[property] = String(value);
    }
    for (const child of node.childNodes ?? node.children ?? []) update(child);
  };
  update(root);
  root.querySelectorAll?.('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
}

// Called once, before application data is rendered. Only original markup is scanned.
export function initTranslations(root = globalThis.document) {
  if (!root) return;
  try { if (globalThis.window?.localStorage?.getItem('memos-viewer-language') === 'en') language = 'en'; } catch { /* Use Chinese by default. */ }
  const visit = node => {
    if (node.nodeType === 3) {
      const source = node.data.trim();
      if (Object.hasOwn(english, source)) {
        const prefix = node.data.slice(0, node.data.indexOf(source)), suffix = node.data.slice(node.data.indexOf(source) + source.length);
        bind(node, 'data', localized(() => prefix + String(t(source)) + suffix));
      }
      return;
    }
    if (['SCRIPT', 'STYLE', 'SVG'].includes(node.tagName)) return;
    // An option without an explicit value otherwise submits its translated label.
    if (node.tagName === 'OPTION' && !node.hasAttribute('value')) node.value = node.textContent;
    for (const name of ['title', 'placeholder', 'aria-label', 'alt', 'data-label']) {
      const source = node.getAttribute?.(name);
      if (Object.hasOwn(english, source)) attr(node, name, t(source));
    }
    for (const child of node.childNodes ?? node.children ?? []) visit(child);
  };
  visit(root);
  root.querySelectorAll?.('[data-language]').forEach(button => {
    button.addEventListener('click', () => setLanguage(button.dataset.language, root));
  });
  setLanguage(language, root);
}

// Local API messages stay unchanged on the wire. Translate known UI-facing messages
// at presentation time; retain unknown host errors and cloud responses verbatim.
const errorTemplates = [
  '请求失败：{0}', 'Space 已创建，但绑定失败：{0}',
  'Space 创建失败或结果未确认，请核对后再创建：{0}',
  '{0} 暂无可验证的本地历史读取器，不能上传历史会话',
  'MemOS {0} 响应格式无效', 'MemOS {0} 业务错误 {1}', 'MemOS {0} 响应缺少 data',
  'MemOS {0} data 格式无效', 'MemOS {0} 响应缺少主题列表',
];
export function errorText(message) {
  if (isLocalized(message) || typeof message !== 'string') return message;
  if (Object.hasOwn(english, message)) return t(message);
  for (const source of errorTemplates) {
    const pattern = '^' + source.split(/\{\d+\}/).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('([\\s\\S]*?)') + '$';
    const match = message.match(new RegExp(pattern));
    if (match) return t(source, ...match.slice(1).map(errorText));
  }
  return message;
}
