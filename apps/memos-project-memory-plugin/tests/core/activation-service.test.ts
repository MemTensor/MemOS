import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { PluginService } from '../../src/server/service.ts';

test('unbound events and stale search IDs are normal inactivity, not sessions or diagnostics', async t => {
    const dir = mkdtempSync(join(tmpdir(), 'pm-activation-'));
    const service = new PluginService(dir, { codexRoots: [] });
    t.after(() => { service.close(); rmSync(dir, { recursive: true, force: true }); });
    const event = { agentType: 'claude-code', nativeSessionId: 'main', cwd: '/workspace', event: 'turn-start' as const, turnKey: 'turn', records: [{ sourceId: 'u', raw: { role: 'user', content: 'private task' } }] };
    const ignored = await service.event(event);
    assert.equal(ignored.sessionId, ''); assert.equal(ignored.context, '');
    for (const table of ['sessions', 'tasks', 'turns', 'traces', 'batches', 'recalls', 'diagnostics']) assert.equal(service.store.rows(`SELECT * FROM ${table}`).length, 0, table);
    const project = service.store.bindProject('Workspace', '/workspace', 'space', service.config.value.baseUrl, 'claude-code');
    service.cloud.call = async () => ({ topic_detail_list: [] }) as any;
    const replay = await service.event({ ...event, nativeSessionId: 'old-history', event: 'session-end', records: [{ sourceId: 'old', raw: { role: 'user', content: 'old' , timestamp: '2020-01-01T00:00:00.000Z' } }] });
    assert.equal(replay.sessionId, ''); assert.equal(service.store.rows('SELECT * FROM sessions').length, 0);
    event.records[0]!.raw = { ...event.records[0]!.raw, timestamp: new Date().toISOString() } as typeof event.records[0]['raw'];
    const active = await service.event(event);
    assert.ok(active.sessionId); assert.ok(active.conversationId);
    const other = await service.event({ ...event, agentType: 'pi' });
    assert.equal(other.sessionId, '');
    service.store.unbind(project.scopeId, 'space');
    const traces = service.store.rows('SELECT * FROM traces');
    const recalls = service.store.rows('SELECT * FROM recalls');
    const stopped = await service.event({ ...event, records: [{ sourceId: 'later', raw: { role: 'assistant', content: 'after unbind' } }] });
    assert.equal(stopped.context, '');
    assert.deepEqual(service.store.rows('SELECT * FROM traces'), traces);
    const search = await service.search({ sessionId: active.sessionId, conversationId: active.conversationId!, query: 'memory' });
    assert.equal(search.status, 'UNAVAILABLE');
    assert.deepEqual(service.store.rows('SELECT * FROM recalls'), recalls);
    assert.equal(service.store.rows('SELECT * FROM diagnostics').length, 0);
    assert.ok(service.store.session(active.sessionId));
});

test('a reply from an earlier binding window cannot populate the re-bound session', async t => {
    const dir = mkdtempSync(join(tmpdir(), 'pm-rebind-recall-'));
    const service = new PluginService(dir, { codexRoots: [] });
    t.after(() => { service.close(); rmSync(dir, { recursive: true, force: true }); });
    const project = service.store.bindProject('Workspace', '/workspace', 'space', service.config.value.baseUrl, 'claude-code');
    let release!: () => void, started!: () => void;
    const waiting = new Promise<void>(resolve => { release = resolve; });
    const reading = new Promise<void>(resolve => { started = resolve; });
    service.cloud.call = async () => { started(); await waiting; return { topic_detail_list: [{ id: 'old', topic_name: 'Stale', topic_summary: 'old binding' }] } as any; };
    const response = service.event({ agentType: 'claude-code', nativeSessionId: 'main', cwd: '/workspace', event: 'turn-start', turnKey: 'turn' });
    await reading;
    const previous = service.store.memory.get(project.scopeId)!.enabledAt!;
    service.store.unbind(project.scopeId, 'space'); service.store.bind(project.scopeId, 'space', service.config.value.baseUrl);
    service.store.db.prepare('UPDATE capture_windows SET startedAt=? WHERE scopeId=? AND endedAt IS NULL').run(new Date(Date.parse(previous) + 1).toISOString(), project.scopeId);
    release();
    assert.equal((await response).context, '');
    assert.equal(service.store.row('SELECT overview FROM sessions')?.overview, null);
    assert.equal(service.store.rows('SELECT * FROM recalls').length, 0);
});
