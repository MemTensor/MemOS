import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { test } from 'node:test';
import { PluginService } from '../../src/server/service.ts';
import { installAdapter } from '../../src/adapters/installer.ts';

test('WorkBuddy refresh backfills the host title, follows manual renames and respects scope and revision', async t => {
    const home = await mkdtemp(join(tmpdir(), 'workbuddy-title-'));
    const service = new PluginService(join(home, 'plugin'), {home, codexRoots: []});
    t.after(async () => { service.close(); await rm(home, {recursive:true, force:true}); });
    await installAdapter('workbuddy', {home});
    const cwd = join(home, 'project'), alias = join(home, 'alias');
    await mkdir(cwd);
    await symlink(cwd, alias);
    const {scopeId} = service.store.bindProject('project', cwd, 'space', service.config.value.baseUrl, 'workbuddy');
    const session = service.store.registerSession({agentType:'workbuddy', nativeSessionId:'s1', cwd});
    const title = () => service.store.session(session.id)?.title;
    const native = new DatabaseSync(join(home,'.workbuddy/workbuddy.db'));
    t.after(() => native.close());
    native.exec('CREATE TABLE sessions(id TEXT PRIMARY KEY,cwd TEXT,title TEXT,custom_title TEXT,updated_at INTEGER,deleted_at INTEGER,transport TEXT)');
    native.prepare("INSERT INTO sessions VALUES ('s1',?,NULL,NULL,1,NULL,'local')").run(alias);
    await service.refreshSessionTitles();
    assert.equal(title(), null);
    native.exec("UPDATE sessions SET title='Generated', updated_at=2");
    await service.refreshSessionTitles();
    assert.equal(title(), 'Generated');
    native.exec("UPDATE sessions SET custom_title='Renamed', updated_at=3");
    await service.refreshSessionTitles();
    assert.equal(title(), 'Renamed');
    native.exec("UPDATE sessions SET custom_title='Stale', updated_at=2");
    await service.refreshSessionTitles();
    assert.equal(title(), 'Renamed');
    native.exec("UPDATE sessions SET custom_title=NULL, updated_at=4");
    await service.refreshSessionTitles();
    assert.equal(title(), 'Generated');
    service.store.unbind(scopeId,'space');
    native.exec("UPDATE sessions SET custom_title='After unbind', updated_at=5");
    await service.refreshSessionTitles();
    assert.equal(title(), 'Generated');
});
